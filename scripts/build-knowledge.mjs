// Packs web/knowledge/*.md into one TypeScript module the Ask endpoint imports.
// Run after changing a knowledge file: npm run knowledge. `npm run validate` fails if the module is stale.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "web/knowledge");
const out = join(root, "web/app/api/ask/knowledge.generated.ts");

export function render() {
  const docs = readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => {
    const text = readFileSync(join(dir, f), "utf8").trim();
    return { id: f.replace(/\.md$/, ""), title: text.split("\n")[0].replace(/^#\s*/, ""), text };
  });
  return `// GENERATED by scripts/build-knowledge.mjs from web/knowledge/*.md. Do not edit.
export const KNOWLEDGE: { id: string; title: string; text: string }[] = ${JSON.stringify(docs, null, 2)};
`;
}
// The content pack the live guide downloads: guides, contacts, rubrics and the job aids for Search.
const packOut = join(root, "web/app/api/content/content.generated.ts");
const readJsonDir = (d) => readdirSync(join(root, d)).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(root, d, f), "utf8")));
export function knowledgeSections() {
  return readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => {
    const [head, ...parts] = readFileSync(join(dir, f), "utf8").trim().split(/\n## /);
    const [titleLine, ...intro] = head.split("\n");
    const sections = [{ heading: "Overview", text: intro.join("\n").trim() }, ...parts.map((p) => { const [h, ...rest] = p.split("\n"); return { heading: h.trim(), text: rest.join("\n").trim() }; })];
    return { title: titleLine.replace(/^#\s*/, ""), sections: sections.filter((x) => x.text) };
  });
}
export function renderPack() {
  const body = { lessons: readJsonDir("web/guides"), contacts: readJsonDir("web/contacts"), rubrics: readJsonDir("web/rubrics"), knowledge: knowledgeSections() };
  // The version is a fingerprint of the content, so it changes exactly when the content does.
  const version = createHash("sha256").update(JSON.stringify(body)).digest("hex").slice(0, 12);
  return `// GENERATED by scripts/build-knowledge.mjs from web/guides, web/contacts, web/rubrics, web/knowledge. Do not edit.
export const CONTENT_PACK = ${JSON.stringify({ version, ...body }, null, 1)};
`;
}
export const isStale = () => !existsSync(out) || readFileSync(out, "utf8") !== render() || !existsSync(packOut) || readFileSync(packOut, "utf8") !== renderPack();

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(out, render());
  writeFileSync(packOut, renderPack());
  console.log(`Knowledge packed: ${readdirSync(dir).filter((f) => f.endsWith(".md")).length} documents → web/app/api/ask/knowledge.generated.ts and web/app/api/content/content.generated.ts`);
}
