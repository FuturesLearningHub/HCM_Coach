// HCM Coach extension build (Offline mode).
// 1. Validates lessons, contacts and rubrics against the shared schemas.
// 2. Bundles that content into the extension (no fetching at runtime).
// 3. Generates manifest.json with host permissions limited to the lessons' allowedDomains.
// 4. Bundles background, content script and side panel.
// 5. Fails the build if any network API appears in the source or the bundle.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { loadContent } from "../scripts/validate-content.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const MODE = process.env.HCM_COACH_MODE || "offline";
const GUIDE = MODE === "guide";
// Live content is also opt-in and guide-only: the guide downloads its guides and job aids from this one server,
// so publishing an update does not need a new extension file.
const CONTENT_URL = (process.env.HCM_COACH_CONTENT_URL || "").replace(/\/+$/, "");
const LIVE = !!CONTENT_URL;
const ORIGINS = CONTENT_URL ? [CONTENT_URL] : [];
const outName = GUIDE ? `dist-guide${LIVE ? "-live" : ""}` : "dist";
const dist = join(here, outName);
const gen = join(here, "src/generated");
const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));
const fail = (msg) => { console.error(`\n✖ BUILD FAILED: ${msg}\n`); process.exit(1); };

// offline: watches the practice sites named in web/lessons and checks each step itself.
// guide:   a read-along guide from web/guides. No site access and no page script, so it cannot see any page.
if (LIVE && !GUIDE) fail("HCM_COACH_CONTENT_URL is only supported with HCM_COACH_MODE=guide.");
if (LIVE && !/^https:\/\/[a-z0-9.-]+$/.test(CONTENT_URL) && !/^http:\/\/localhost:\d+$/.test(CONTENT_URL)) fail("HCM_COACH_CONTENT_URL must be an https origin with no path, e.g. https://example.org");
if (MODE !== "offline" && MODE !== "guide") fail(`HCM_COACH_MODE=${MODE} is not implemented. Use "offline" or "guide".`);

// ── 1. Content ────────────────────────────────────────────────────────────────
const { errors, lessons, contacts, rubrics } = GUIDE ? loadContent("web/guides", false) : loadContent("web/lessons", true);
if (errors.length) fail("content does not match the schemas:\n  " + errors.join("\n  "));

// A wildcard would give the extension access to sites other people control. Name each host exactly.
const wild = lessons.flatMap((l) => (l.allowedDomains ?? []).filter((d) => d.startsWith("*.")).map((d) => `${l.id}: ${d}`));
if (wild.length) fail("wildcard allowedDomains are not allowed in offline builds. Use exact hostnames.\n  " + wild.join("\n  "));

// Job aids for the offline Search view (guide builds only). Split at "## " headings so results are one step group each.
const knowledgeDir = join(root, "web/knowledge");
const knowledge = !GUIDE ? [] : readdirSync(knowledgeDir).filter((f) => f.endsWith(".md")).sort().map((f) => {
  const [head, ...parts] = readFileSync(join(knowledgeDir, f), "utf8").trim().split(/\n## /);
  const [titleLine, ...intro] = head.split("\n");
  const sections = [{ heading: "Overview", text: intro.join("\n").trim() }, ...parts.map((p) => { const [h, ...rest] = p.split("\n"); return { heading: h.trim(), text: rest.join("\n").trim() }; })];
  return { title: titleLine.replace(/^#\s*/, ""), sections: sections.filter((x) => x.text) };
});

// ── 2. Generated modules ──────────────────────────────────────────────────────
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
mkdirSync(gen, { recursive: true });
writeFileSync(join(gen, "content.ts"),
`// GENERATED by build.mjs from web/lessons, web/contacts, web/rubrics. Do not edit.
import type { Lesson, ContactsDirectory, Rubric } from "../../../shared/types";
export const MODE: string = ${JSON.stringify(MODE)};
export const CONTENT_URL: string = ${JSON.stringify(CONTENT_URL)};
export const VERSION = ${JSON.stringify(pkg.version)};
export const BUILT = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const KNOWLEDGE: { title: string; sections: { heading: string; text: string }[] }[] = ${JSON.stringify(knowledge)};
export const RAW_LESSONS: unknown[] = ${JSON.stringify(lessons)};
export const RAW_CONTACTS: unknown[] = ${JSON.stringify(contacts)};
export const RAW_RUBRICS: unknown[] = ${JSON.stringify(rubrics)};
export type { Lesson, ContactsDirectory, Rubric };
`);
// Precompiled validators: Ajv normally compiles with new Function(), which the extension CSP forbids.
const readSchema = (n) => JSON.parse(readFileSync(join(root, "shared", n), "utf8"));
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
const schemas = { lesson: readSchema("lesson.schema.json"), contacts: readSchema("contacts.schema.json"), rubric: readSchema("rubric.schema.json") };
for (const s of Object.values(schemas)) ajv.addSchema(s);
writeFileSync(join(gen, "validators.js"), standaloneCode(ajv, { validateLesson: schemas.lesson.$id, validateContacts: schemas.contacts.$id, validateRubric: schemas.rubric.$id }));
writeFileSync(join(gen, "validators.d.ts"),
`type V = ((data: unknown) => boolean) & { errors?: { instancePath: string; message?: string }[] | null };
export const validateLesson: V; export const validateContacts: V; export const validateRubric: V;
`);

// ── 3. Manifest ───────────────────────────────────────────────────────────────
const toPattern = (d) => {
  const host = d.replace(/^\*\./, "").split(":")[0];
  const local = host === "localhost" || /^127\./.test(host);
  return `${local ? "http" : "https"}://${d}/*`;
};
const hostPatterns = GUIDE ? [] : [...new Set(lessons.flatMap((l) => l.allowedDomains).map(toPattern))].sort();
const manifest = {
  manifest_version: 3,
  name: GUIDE ? (LIVE ? "HCM Coach" : "HCM Coach: HCM Academy Guide") : "HCM Coach",
  ...(LIVE ? { version_name: `${pkg.version} live` } : {}),
  short_name: "HCM Coach",
  version: pkg.version,
  description: GUIDE
    ? (LIVE ? "A step-by-step guide that sits beside your work. It cannot see or change any page. It downloads its own guide updates."
      : "A step-by-step guide that sits beside your work. It cannot see or change any page, and has no network access.")
    : "Coaches you through a real work process, step by step. Offline build: no network access.",
  minimum_chrome_version: "116",
  icons: { 16: "icons/16.png", 48: "icons/48.png", 128: "icons/128.png" },
  action: { default_title: GUIDE ? "Open the guide" : "Open the coach" },
  side_panel: { default_path: "sidepanel.html" },
  background: { service_worker: "background.js", type: "module" },
  permissions: ["storage", "sidePanel"],
  ...(GUIDE ? {} : { host_permissions: hostPatterns, content_scripts: [{ matches: hostPatterns, js: ["content.js"], run_at: "document_idle" }] }),
  content_security_policy: { extension_pages: `script-src 'self'; object-src 'self'; connect-src ${ORIGINS.length ? ORIGINS.join(" ") : "'none'"}` },
};
writeFileSync(join(dist, "manifest.json"), JSON.stringify(manifest, null, 2));

// ── 4. Bundles ────────────────────────────────────────────────────────────────
const common = { bundle: true, minify: true, target: "chrome116", legalComments: "none", logLevel: "warning",
  alias: { "#content": join(here, LIVE ? "src/lib/content-on.ts" : "src/lib/content-off.ts") },
  define: { "process.env.NODE_ENV": '"production"' } };
await build({ ...common, entryPoints: [join(here, "src/background.ts")], outfile: join(dist, "background.js"), format: "esm" });
if (!GUIDE) await build({ ...common, entryPoints: [join(here, "src/content.ts")], outfile: join(dist, "content.js"), format: "iife" });
await build({ ...common, entryPoints: [join(here, "src/sidepanel/main.tsx")], outdir: dist, entryNames: "sidepanel", assetNames: "assets/[name]", format: "iife",
  loader: { ".woff2": "file", ".png": "file", ".svg": "file" } });
cpSync(join(here, "src/sidepanel/index.html"), join(dist, "sidepanel.html"));
cpSync(join(here, "assets/icons"), join(dist, "icons"), { recursive: true });
cpSync(join(here, GUIDE ? (LIVE ? "SECURITY-APP.md" : "SECURITY-GUIDE.md") : "SECURITY.md"), join(dist, "SECURITY.md"));

// ── 5. Network-call check ─────────────────────────────────────────────────────
const FORBIDDEN = [
  ["fetch(", /\bfetch\s*\(/], ["XMLHttpRequest", /\bXMLHttpRequest\b/], ["WebSocket", /\bWebSocket\b/],
  ["sendBeacon", /\bsendBeacon\b/], ["EventSource", /\bEventSource\b/], ["importScripts", /\bimportScripts\s*\(/],
  ["remote script/style/import", /(?:src|href)\s*=\s*["']?(?:https?:)?\/\/|import\s*\(\s*["'`]https?:|@import\s+(?:url\()?["']?https?:|url\(\s*["']?https?:/],
  ["externally_connectable", /externally_connectable/],
];
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const scannable = (p) => /\.(js|ts|tsx|css|html|json)$/.test(p);
const hits = [];
// content-on.ts is the only source file allowed to hold network code. It is bundled only into
// builds that turn live content on (the aliases above), and the bundle of every build is scanned in full.
const NET_FILES = [join("src", "lib", "content-on.ts")];
const expected = LIVE ? 1 : 0;
const allowed = (file, name) => name === "fetch(" && (NET_FILES.some((f) => file.endsWith(f)) || (expected > 0 && file === join(dist, "sidepanel.js")));
for (const file of [...walk(join(here, "src")), ...walk(dist)].filter(scannable)) {
  const lines = readFileSync(file, "utf8").split("\n");
  lines.forEach((line, i) => { for (const [name, re] of FORBIDDEN) if (re.test(line) && !allowed(file, name)) hits.push(`${relative(root, file)}:${i + 1}  ${name}`); });
}
if (expected > 0) {
  const panel = readFileSync(join(dist, "sidepanel.js"), "utf8");
  const calls = (panel.match(/\bfetch\s*\(/g) ?? []).length;
  if (calls !== expected) fail(`this build must contain exactly ${expected} network call(s) in the side panel, found ${calls}.`);
  const urls = [...new Set(panel.match(/https?:\/\/[a-z0-9.-]+(?::\d+)?/gi) ?? [])].filter((u) => !/w3\.org|reactjs\.org|react\.dev|fb\.me|json-schema\.org|hcm-coach\.local/.test(u));
  if (urls.some((u) => !ORIGINS.includes(u))) fail("unexpected address in the side panel bundle: " + urls.filter((u) => !ORIGINS.includes(u)).join(", "));
}
if (hits.length) fail("network code found. Offline builds must have none.\n  " + hits.join("\n  "));

const size = (f) => (statSync(join(dist, f)).size / 1024).toFixed(0) + " kB";
console.log(`✔ HCM Coach ${pkg.version} (${MODE}${LIVE ? " + live content" : ""}) built → extension/${outName}
  lessons: ${lessons.map((l) => l.id).join(", ")}
  host_permissions: ${hostPatterns.join(", ") || "none"}${GUIDE ? "\n  content script: none" : ""}
  background.js ${size("background.js")}${GUIDE ? "" : ` · content.js ${size("content.js")}`} · sidepanel.js ${size("sidepanel.js")}
  network-call check: ${expected ? `${expected} call(s), to ${ORIGINS.join(", ")} only` : "clean (source + bundle)"}`);
